def scrub_cite_ban_narratives(obj):
    """Drop CNS ban / block-from-X narratives from cite.json (SEO surface)."""
    if isinstance(obj, dict):
        out = {}
        for key, val in obj.items():
            if key == "refuse" and isinstance(val, str) and any(
                marker in val for marker in SEO_BAN_MARKERS
            ):
                continue
            if key == "refuse" and isinstance(val, dict):
                cleaned = {
                    rk: rv
                    for rk, rv in val.items()
                    if not (
                        isinstance(rv, str)
                        and any(marker in rv for marker in SEO_BAN_MARKERS)
                    )
                }
                out[key] = cleaned
                continue
            if key == "reason" and isinstance(val, str) and any(
                marker in val for marker in SEO_BAN_MARKERS
            ):
                continue
            out[key] = scrub_cite_ban_narratives(val)
        return out
    if isinstance(obj, list):
        return [scrub_cite_ban_narratives(v) for v in obj]
    if isinstance(obj, str):
        text = obj
        for marker in SEO_BAN_MARKERS:
            text = text.replace(marker, "")
        text = text.replace("  ", " ").replace(" .", ".").strip()
        return text
    return obj


def drop_faq_titles(faq: list) -> list:
    """Remove definition-by-negation FAQ rows from machine SEO lists."""
    banned = set(DROP_FAQ_TITLES)
    out = []
    for item in faq or []:
        if isinstance(item, dict) and item.get("q") in banned:
            continue
        out.append(item)
    return out


